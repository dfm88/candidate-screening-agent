"""The API contract: request, response and SSE event models. The frontend builds against these, and its types in
frontend/src/api.ts mirror this file.

    GET  /api/apply-form                 → ApplyForm
    POST /api/applications               ApplicationRequest → 201 ApplicationCreated · 403 wrong access code
    GET  /api/chat/{token}               → ChatSession · 404 unknown token
    POST /api/chat/{token}/messages      CandidateMessage → 202 MessageAccepted · 409 chat closed
    GET  /api/chat/{token}/events        SSE: `message` ChatMessage (id = message id, replayed after Last-Event-ID),
                                              `typing` Typing, `status` ChatStatus
"""

from datetime import datetime
from enum import StrEnum
from typing import Annotated
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from screening.config import Country, Language
from screening.domain import Status

# --- Apply ------------------------------------------------------------------------------------------------------


class Vacancy(BaseModel):
    id: str
    name: str
    city: str
    country: Country


class ApplyForm(BaseModel):
    """What the apply page needs: the client, its vacancies, and whether to ask for the access code."""

    client_name: str
    vacancies: list[Vacancy]
    access_code_required: bool


class ApplicationRequest(BaseModel):
    submission_id: UUID = Field(
        description="Generated by the apply page once per form: a retried submit returns the same chat."
    )
    full_name: Annotated[str, StringConstraints(strip_whitespace=True, min_length=2, max_length=120)]
    phone: Annotated[str, StringConstraints(strip_whitespace=True, pattern=r"^\+?[0-9][0-9 ()-]{6,19}$")]
    vacancy_location_id: str
    language: Language
    whatsapp_opt_in: bool = False
    access_code: str | None = None


class ApplicationCreated(BaseModel):
    candidate_id: UUID
    chat_url: str = Field(description="Path of the candidate's chat, e.g. /chat/{token}.")


# --- Chat -------------------------------------------------------------------------------------------------------


class ChatSession(BaseModel):
    """The chat header, and the status that says whether the chat still takes messages."""

    persona_name: str
    client_name: str
    first_name: str
    language: Language
    status: Status


class CandidateMessage(BaseModel):
    text: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=2000)]
    client_id: Annotated[str, StringConstraints(min_length=1, max_length=64)] = Field(
        description="Generated by the client per message: a retried send is stored once, and the echo carries it."
    )


class MessageAccepted(BaseModel):
    id: int


class Author(StrEnum):
    CANDIDATE = "candidate"
    ASSISTANT = "assistant"


class ChatMessage(BaseModel):
    """One chat bubble. Candidate messages are echoed too, so every open tab shows them."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    author: Author
    text: str
    # Suggested replies under this bubble; tapping one sends its text. Free text always works.
    quick_replies: list[str] = []
    client_id: str | None = None
    created_at: datetime


class Typing(BaseModel):
    active: bool


class ChatStatus(BaseModel):
    status: Status


ChatEvent = ChatMessage | Typing | ChatStatus
